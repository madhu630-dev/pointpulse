const PDFDocument = require('pdfkit-table');
const crypto = require('crypto');
const supabase = require('../db/supabase');
const { run, get, all } = require('../db/database');

// Build branded PDF helper
function createBrandedDoc(title, subtitle, author = 'PointPulse Platform') {
    const doc = new PDFDocument({
        margin: 40,
        size: 'A4',
        bufferPages: true
    });

    // --- COVER PAGE ---
    doc.rect(0, 0, doc.page.width, doc.page.height).fill('#0f172a'); // Dark slate background

    // Decorative top accent bar
    doc.rect(40, 40, doc.page.width - 80, 4).fill('#6366f1');

    doc.fillColor('#ffffff').fontSize(32).font('Helvetica-Bold')
       .text('POINTPULSE', 40, 180, { tracking: 2 });
    
    doc.fillColor('#94a3b8').fontSize(14).font('Helvetica')
       .text('Account Management & Rewards Intelligence Platform', 40, 225);

    doc.rect(40, 255, 60, 2).fill('#6366f1');

    doc.fillColor('#f8fafc').fontSize(22).font('Helvetica-Bold')
       .text(title, 40, 280, { width: 500 });

    if (subtitle) {
        doc.fillColor('#cbd5e1').fontSize(13).font('Helvetica')
           .text(subtitle, 40, 315, { width: 500 });
    }

    // Metadata card
    const now = new Date();
    const metaY = 460;
    doc.roundedRect(40, metaY, doc.page.width - 80, 110, 8)
       .fillOpacity(0.1).fill('#ffffff').strokeOpacity(0.2).stroke('#ffffff');

    doc.fillOpacity(1.0);
    doc.fillColor('#94a3b8').fontSize(10).font('Helvetica-Bold')
       .text('REPORT METADATA', 60, metaY + 15);

    doc.fillColor('#ffffff').fontSize(10).font('Helvetica')
       .text(`Generated On: ${now.toLocaleDateString()} at ${now.toLocaleTimeString()}`, 60, metaY + 35)
       .text(`Classification: Confidential / Internal`, 60, metaY + 52)
       .text(`Generated By: ${author}`, 60, metaY + 69)
       .text(`Security Notice: Sensitive credentials and authentication tokens are strictly redacted.`, 60, metaY + 86);

    // Decorative bottom footer
    doc.fillColor('#64748b').fontSize(9).font('Helvetica')
       .text('PointPulse Automated Report Generation Service • Confidential', 40, doc.page.height - 50, { align: 'center', width: doc.page.width - 80 });

    // Add content page
    doc.addPage({ margin: 40 });
    return doc;
}

// Add headers & footers across all buffered pages
function finalizeDoc(doc) {
    const range = doc.bufferedPageRange();
    for (let i = range.start + 1; i < range.start + range.count; i++) {
        doc.switchToPage(i);
        // Header
        doc.fillColor('#64748b').fontSize(8).font('Helvetica')
           .text('PointPulse Official Report', 40, 20, { align: 'left' });
        doc.text(new Date().toLocaleDateString(), doc.page.width - 140, 20, { align: 'right', width: 100 });
        doc.moveTo(40, 30).lineTo(doc.page.width - 40, 30).strokeColor('#e2e8f0').lineWidth(0.5).stroke();

        // Footer
        doc.moveTo(40, doc.page.height - 30).lineTo(doc.page.width - 40, doc.page.height - 30).strokeColor('#e2e8f0').lineWidth(0.5).stroke();
        doc.fillColor('#64748b').fontSize(8).font('Helvetica')
           .text(`Page ${i + 1} of ${range.count}`, 40, doc.page.height - 22, { align: 'center', width: doc.page.width - 80 });
    }
}

// Generate Admin Detailed Report
const generateReport = async (req, res) => {
    const user = req.user;
    const { reportType, userId, rewardId, statusFilter, classificationFilter } = req.body;

    // Regular users can only request their own reports
    const targetUserId = (user.role === 'admin' && userId) ? userId : (user.role === 'admin' ? null : user.id);

    try {
        const { data: allAccounts } = await supabase.from('Users').select('id, profile_no, email, server, status').order('profile_no', { ascending: true });
        const metaRows = await all(`SELECT account_id, user_id, classification FROM account_metadata`);
        const metaMap = new Map();
        metaRows.forEach(m => metaMap.set(m.account_id, m));

        const laptopUser = await get(`SELECT id FROM app_users WHERE lower(email) = 'laptopmew1@gmail.com'`);
        const primaryOperatorId = laptopUser ? laptopUser.id : 1;

        let accounts = (allAccounts || []).map(a => {
            const m = metaMap.get(a.id);
            return {
                ...a,
                user_id: (m && m.user_id && m.user_id !== 1) ? m.user_id : primaryOperatorId,
                classification: m ? m.classification : 'new'
            };
        });

        if (targetUserId) {
            accounts = accounts.filter(a => a.user_id == targetUserId);
        }
        if (statusFilter && statusFilter !== 'all') {
            accounts = accounts.filter(a => a.status === statusFilter);
        }
        if (classificationFilter && classificationFilter !== 'all') {
            accounts = accounts.filter(a => a.classification === classificationFilter);
        }
        const accountIds = (accounts || []).map(a => a.id);

        let latestPoints = new Map();
        if (accountIds.length > 0) {
            const { data: points } = await supabase.from('Points').select('user_id, points').in('user_id', accountIds).order('id', { ascending: false });
            (points || []).forEach(p => {
                if (!latestPoints.has(p.user_id)) latestPoints.set(p.user_id, p.points);
            });
        }

        let redemptions = [];
        if (accountIds.length > 0) {
            const { data: redData } = await supabase.from('Redemptions').select('*').in('user_id', accountIds).order('redeemed_at', { ascending: false });
            redemptions = redData || [];
        }

        // Fetch users map for sectioning
        const allUsersList = await all(`SELECT id, name, email FROM app_users`);
        const userMap = new Map();
        allUsersList.forEach(u => userMap.set(u.id, u));

        // Create PDF Document
        const reportTitle = `${reportType || 'Account & Performance'} Detailed Report`;
        const subtitle = targetUserId ? `Filtered for ${userMap.get(Number(targetUserId))?.name || 'User #' + targetUserId}` : 'Comprehensive Enterprise Overview';
        const doc = createBrandedDoc(reportTitle, subtitle, user.name);

        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', `attachment; filename="PointPulse_Report_${Date.now()}.pdf"`);
        doc.pipe(res);

        // --- SUMMARY STATS SECTION ---
        doc.fillColor('#0f172a').fontSize(16).font('Helvetica-Bold')
           .text('Executive Summary', 40, 45);
        doc.moveDown(0.5);

        const totalAccounts = accounts ? accounts.length : 0;
        const activeAccounts = (accounts || []).filter(a => a.status === 'active').length;
        const bannedAccounts = (accounts || []).filter(a => a.status === 'banned').length;
        let totalPts = 0;
        (accounts || []).forEach(a => totalPts += (latestPoints.get(a.id) || 0));

        // Summary KPI Table
        const kpiTable = {
            headers: [
                { label: 'Total Managed Accounts', property: 'total', width: 120 },
                { label: 'Active Status', property: 'active', width: 100 },
                { label: 'Banned Status', property: 'banned', width: 100 },
                { label: 'Total Current Points', property: 'points', width: 110 },
                { label: 'Total Redemptions', property: 'redemps', width: 85 }
            ],
            datas: [{
                total: String(totalAccounts),
                active: String(activeAccounts),
                banned: String(bannedAccounts),
                points: totalPts.toLocaleString(),
                redemps: String(redemptions.length)
            }]
        };

        await doc.table(kpiTable, {
            prepareHeader: () => doc.font('Helvetica-Bold').fontSize(9).fillColor('#ffffff'),
            prepareRow: () => doc.font('Helvetica-Bold').fontSize(10).fillColor('#1e293b'),
            headerBackgroundColor: '#4f46e5'
        });

        doc.moveDown(1.5);

        // --- DATA SECTION: Group by User if Multi-User ---
        const accountsByUser = {};
        (accounts || []).forEach(a => {
            const uid = a.user_id || 1;
            if (!accountsByUser[uid]) accountsByUser[uid] = [];
            accountsByUser[uid].push(a);
        });

        for (const [uid, uAccounts] of Object.entries(accountsByUser)) {
            const uInfo = userMap.get(Number(uid)) || { name: `User #${uid}`, email: 'System Account' };
            
            doc.fillColor('#4338ca').fontSize(13).font('Helvetica-Bold')
               .text(`Section: ${uInfo.name} (${uInfo.email})`, { underline: true });
            doc.moveDown(0.4);

            const tableData = {
                headers: [
                    { label: 'Prof #', property: 'prof', width: 50 },
                    { label: 'Account Identifier / Email', property: 'email', width: 180 },
                    { label: 'Server', property: 'server', width: 90 },
                    { label: 'Points', property: 'points', width: 75 },
                    { label: 'Class', property: 'class', width: 60 },
                    { label: 'Status', property: 'status', width: 60 }
                ],
                datas: uAccounts.map(a => ({
                    prof: a.profile_no ? String(a.profile_no) : '-',
                    email: a.email,
                    server: a.server || '-',
                    points: (latestPoints.get(a.id) || 0).toLocaleString(),
                    class: (a.classification || 'new').toUpperCase(),
                    status: (a.status || 'active').toUpperCase()
                }))
            };

            await doc.table(tableData, {
                prepareHeader: () => doc.font('Helvetica-Bold').fontSize(8).fillColor('#ffffff'),
                prepareRow: (row, i) => doc.font('Helvetica').fontSize(8).fillColor(i % 2 === 0 ? '#1e293b' : '#334155'),
                headerBackgroundColor: '#1e293b'
            });

            doc.moveDown(1.2);
        }

        // Finalize pages with numbers and headers
        finalizeDoc(doc);
        doc.end();

        // Audit Log
        await run(
            `INSERT INTO audit_logs (actor_id, actor_email, actor_role, action, new_value, result)
             VALUES (?, ?, ?, 'Generated PDF Report', ?, 'success')`,
            [user.id, user.email, user.role, JSON.stringify({ reportType, targetUserId })]
        );

    } catch (error) {
        console.error('Generate Report Error:', error);
        if (!res.headersSent) {
            res.status(500).json({ error: 'Error generating PDF report' });
        }
    }
};

// User Request for Download
const requestDownload = async (req, res) => {
    const user = req.user;
    const { reportType, filters } = req.body;

    try {
        const token = crypto.randomBytes(24).toString('hex');
        const insertRes = await run(
            `INSERT INTO download_requests (user_id, report_type, filters, token, status)
             VALUES (?, ?, ?, ?, 'pending')`,
            [user.id, reportType || 'user_summary', JSON.stringify(filters || {}), token]
        );

        // Notify Admin
        await run(
            `INSERT INTO notifications (recipient_role, category, title, message, reference_id)
             VALUES ('admin', 'download_request', 'Download Permission Request', ?, ?)`,
            [
                `User ${user.name} requested download permission for: ${reportType}.`,
                String(insertRes.lastID)
            ]
        );

        res.json({ success: true, message: 'Download request submitted for administrator approval.' });
    } catch (error) {
        console.error('Request Download Error:', error);
        res.status(500).json({ error: 'Error submitting download request' });
    }
};

// Admin Approve Download Request (Generates secure expiring token)
const approveDownloadRequest = async (req, res) => {
    const requestId = req.params.id;
    try {
        const reqRow = await get(`SELECT * FROM download_requests WHERE id = ?`, [requestId]);
        if (!reqRow) return res.status(404).json({ error: 'Download request not found' });

        const expiresAt = new Date(Date.now() + 24 * 60 * 60 * 1000).toISOString(); // 24 hours expiry
        await run(
            `UPDATE download_requests 
             SET status = 'approved', expires_at = ?, approved_by = ?
             WHERE id = ?`,
            [expiresAt, req.user.id, requestId]
        );

        // Notify User
        await run(
            `INSERT INTO notifications (recipient_role, recipient_id, category, title, message, reference_id)
             VALUES ('user', ?, 'download_approved', 'Download Request Approved', 'Your requested report is ready to download. Access expires in 24 hours.', ?)`,
            [reqRow.user_id, reqRow.token]
        );

        res.json({ success: true, token: reqRow.token, expiresAt });
    } catch (error) {
        console.error('Approve Download Error:', error);
        res.status(500).json({ error: 'Error approving download' });
    }
};

// Secure Expiring Download Access
const downloadViaToken = async (req, res) => {
    const token = req.params.token;
    try {
        const reqRow = await get(`SELECT * FROM download_requests WHERE token = ?`, [token]);
        if (!reqRow) return res.status(404).send('Invalid download link');

        if (reqRow.status !== 'approved') {
            return res.status(403).send('Download request is not approved');
        }

        const now = new Date().toISOString();
        if (reqRow.expires_at && reqRow.expires_at < now) {
            await run(`UPDATE download_requests SET status = 'expired' WHERE id = ?`, [reqRow.id]);
            return res.status(410).send('This secure download link has expired.');
        }

        // Fetch user info & generate report
        const user = await get(`SELECT * FROM app_users WHERE id = ?`, [reqRow.user_id]);
        req.user = user;
        req.body = { reportType: reqRow.report_type, userId: reqRow.user_id };

        return generateReport(req, res);

    } catch (error) {
        console.error('Download Via Token Error:', error);
        res.status(500).send('Error delivering report');
    }
};

module.exports = {
    generateReport,
    requestDownload,
    approveDownloadRequest,
    downloadViaToken
};
